PLAN_SYSTEM = """你是漫剧分镜计划师。你把语义场景块压成 1 分钟（12 段 × 5 秒）的分镜计划。

你的产出是给下游程序读的结构化数据，不是给人看的文章：
只输出一个 JSON 对象，不要代码块围栏、不要解释、不要注释、不要尾随文字。

所有取值必须落在给定槽位名单内；台词只能来自给定语义 md，不得编造。
每条视频先定「1 个场景 + 最多 5 个人物道具」，再排 12 段、每段 5 秒的动作与台词。"""


def plan_user(book, ep, ep_title, sem_md, want_videos, ep_blocks, has_lines=True):
    no_line_note = "" if has_lines else (
        "\n【特别注意】本集语义 md 里没有任何 `%s-L###` 台词行，因此**所有 dialogue 必须是 null**，"
        "全部用可见动作推进；不得编造台词。\n" % ep)
    hint = book.hint_text()
    mute = book.mute_text()
    return f"""把 {ep}（{ep_title}）压成**恰好 {want_videos} 条** 1 分钟分镜计划，输出 JSON。
{no_line_note}
【槽位合法名单】（只能从这里取，写错即作废）
{book.whitelist_text()}
{hint}{mute} 是哑角：可以出现在 characters，但绝不能当说话人。

【输出结构】
{{
  "episode": "{ep}",
  "episode_title": "{ep_title}",
  "videos": [
    {{
      "title": "四到八字概括本条主线",
      "src": "{ep}-S01–S03 / R0288–R0311",
      "logline": "一句话剧情，不超过 40 字",
      "scene": "一个场景槽位名",
      "characters": ["人物槽位名"],
      "props": ["道具槽位名，没有就空数组"],
      "segments": [
        {{"i": 1, "action": "六到二十五字的可见动作", "dialogue": null}},
        {{"i": 2, "action": "可见动作", "dialogue": {{"speaker": "人物", "delivery": "油滑", "text": "不超过二十一字", "line": "{ep}-L005"}}}}
      ]
    }}
  ]
}}

【硬性规则】
1. videos **恰好 {want_videos} 条，不多不少**（少了要拆，多了要合）；每条 segments 恰好 12 项，i 从 1 到 12 连续。
2. 每条视频只能有 1 个 scene；12 段共用这个场景。characters + props 合计不超过 5 个（加场景共 6 个参考图槽）。
3. 允许大幅压缩：一条视频只讲一条主线，次要支线直接舍弃；无名众统一用「护卫甲」；同功能配角合并。
4. action 每条 6–25 字，只写镜头拍得到的东西：谁 + 身体/武器/物件怎么动 + 可见结果。
   - 不能写心理、推断、因果、时间过渡：心想／暗忖／原来／于是／终于／只见／因为／所以／语毕／话一说完／就在此时／另外这边／镜头带到／彷佛／宛如／全神贯注 等一律禁止。
   - 比喻改成物理动作：「杀气腾腾」→「刀锋压低，指节捏白」；「黯然神伤」→「垂眼抿唇，指尖松开」。
   - 动作里不要用「说」「道」「喊」开头。
5. dialogue 为 null 或对象；speaker 必须在 characters 内，且不是哑角；delivery 是 2–4 字语态标签（油滑／悍然／冷讥／急切／沉痛…）。
6. dialogue.text 不超过 21 字（标点算字）。能逐字用原文且不超长，就填真实 line（如 {ep}-L012）；
   **原句超过 21 字必须压缩改写**：留主干、删称呼与客套、保留说话人语气，line 填 ""。
   例：「大仔，七重冥王及魔魁之女都死了，非凡公子也不见踪影，武林突然太平，这种日子真无聊。」
   → 「七重冥王都死了，太平日子真无聊。」（18 字，line 填 ""）。绝不编造原文没有的台词。
7. 一条视频里 dialogue 总数 8–14 条为宜；宁可少而准，不要堆废话。纯叙述段可以整段没有台词。
8. 禁止英文（原文拟声除外）；不要出现「字幕」「旁白」「配乐」这类词。
9. 台词按剧情顺序分布，不要挤在前三段；每段最多 1 条台词。

【本集语义 md】（共 {ep_blocks} 个场景块，它是唯一台词来源）
{sem_md}
"""


def repair_user(errors, limit=40):
    lines = "\n".join("%d. %s" % (i + 1, e) for i, e in enumerate(errors[:limit]))
    return f"""你刚才的输出有以下违规，必须全部修正：

{lines}

要求：重新输出**完整**的 JSON（不是补丁、不是 diff），保持原有正确内容，只改违规处。
仍然只输出 JSON 对象本身，不要围栏、不要解释。"""


def patch_user(errors, current, limit=30):
    """定点修补：只让模型重写违规的段，避免整份重出时把对的段改错。"""
    import json as _json
    lines = "\n".join("%d. %s" % (i + 1, e) for i, e in enumerate(errors[:limit]))
